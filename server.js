// Company Debt Payment (Atomic Transaction with Cash Register Integration)
app.post('/api/companies/:id/pay-debt', authenticateToken, async (req, res) => {
  const { amount, payment_mode, company_debt_id, payment_date, notes } = req.body || {};
  const payAmount = Number(amount) || 0;
  const compId = req.params.id;

  if (!compId || payAmount <= 0) {
    return res.status(400).json({ success: false, message: 'تکایە بڕی دروستی پارە بنووسە' });
  }

  const client = await getClient();
  try {
    await client.query('BEGIN');

    // 1. Lock company row
    const compRes = await client.query('SELECT * FROM companies WHERE id = $1 FOR UPDATE', [compId]);
    const company = compRes.rows[0];
    if (!company) {
      await client.query('ROLLBACK');
      return res.status(404).json({ success: false, message: 'کۆمپانیا نەدۆزرایەوە' });
    }

    const prevDebt = Number(company.current_debt) || 0;
    if (payAmount > prevDebt) {
      await client.query('ROLLBACK');
      return res.status(400).json({
        success: false,
        message: 'بڕی پارەدان ناتوانێت لە کۆی قەرزی ماوەی کۆمپانیا زیاتر بێت',
      });
    }

    const newDebt = Math.max(0, prevDebt - payAmount);
    const dateStr = payment_date || formatDate();

    // 2. Update company balance
    await client.query(
      'UPDATE companies SET current_debt = $1, total_paid = total_paid + $2, updated_at = NOW() WHERE id = $3',
      [newDebt, payAmount, compId]
    );

    // 3. Allocate to company_debts
    let targetedDebtId = null;

    if (payment_mode === 'specific_invoice' && company_debt_id) {
      const sDebtRes = await client.query(
        'SELECT * FROM company_debts WHERE id = $1 AND company_id = $2 FOR UPDATE',
        [company_debt_id, compId]
      );
      const sDebt = sDebtRes.rows[0];
      if (sDebt) {
        targetedDebtId = sDebt.id;
        const curRem = Number(sDebt.remaining_amount) || 0;
        const deduct = Math.min(curRem, payAmount);
        const newRem = curRem - deduct;
        const newStatus = newRem === 0 ? 'paid' : 'partial';

        await client.query(
          'UPDATE company_debts SET remaining_amount = $1, paid_amount = paid_amount + $2, status = $3, updated_at = NOW() WHERE id = $4',
          [newRem, deduct, newStatus, sDebt.id]
        );

        // If amount was greater than this single invoice debt, allocate the remainder FIFO
        let remainingAfterSpecific = payAmount - deduct;
        if (remainingAfterSpecific > 0) {
          const otherDebts = await client.query(
            "SELECT * FROM company_debts WHERE company_id = $1 AND id != $2 AND status != 'paid' ORDER BY id ASC FOR UPDATE",
            [compId, sDebt.id]
          );
          for (const d of otherDebts.rows) {
            if (remainingAfterSpecific <= 0) break;
            const dRem = Number(d.remaining_amount) || 0;
            const subDeduct = Math.min(dRem, remainingAfterSpecific);
            const subNewRem = dRem - subDeduct;
            const subStatus = subNewRem === 0 ? 'paid' : 'partial';
            await client.query(
              'UPDATE company_debts SET remaining_amount = $1, paid_amount = paid_amount + $2, status = $3, updated_at = NOW() WHERE id = $4',
              [subNewRem, subDeduct, subStatus, d.id]
            );
            remainingAfterSpecific -= subDeduct;
          }
        }
      }
    } else {
      // Default: Oldest Debt First (FIFO allocation)
      let remainingToDeduct = payAmount;
      const debtsRes = await client.query(
        "SELECT id, remaining_amount FROM company_debts WHERE company_id = $1 AND status != 'paid' ORDER BY id ASC FOR UPDATE",
        [compId]
      );

      for (const d of debtsRes.rows) {
        if (remainingToDeduct <= 0) break;
        if (!targetedDebtId) targetedDebtId = d.id;
        const dRem = Number(d.remaining_amount) || 0;
        const deduct = Math.min(dRem, remainingToDeduct);
        const newDRem = dRem - deduct;
        const newStatus = newDRem === 0 ? 'paid' : 'partial';

        await client.query(
          'UPDATE company_debts SET remaining_amount = $1, paid_amount = paid_amount + $2, status = $3, updated_at = NOW() WHERE id = $4',
          [newDRem, deduct, newStatus, d.id]
        );
        remainingToDeduct -= deduct;
      }
    }

    // 4. Record payment history
    const payInsRes = await client.query(
      `INSERT INTO company_debt_payments (company_id, company_debt_id, amount, cash_account_id, received_by, notes, payment_date, created_at)
       VALUES ($1, $2, $3, 1, $4, $5, $6, NOW())
       RETURNING id`,
      [compId, targetedDebtId, payAmount, req.user.user_id, notes || 'وەرگرتنەوەی قەرزی کۆمپانیا', dateStr]
    );
    const paymentId = payInsRes.rows[0]?.id;

    // 5. Integrate with Cash Register (Inflow as COMPANY_DEBT_PAYMENT)
    await recordCashTransaction(client, {
      cashAccountId: 1,
      transactionType: 'COMPANY_DEBT_PAYMENT',
      direction: 'IN',
      amount: payAmount,
      referenceType: 'company_debt_payment',
      referenceId: paymentId,
      description: `وەرگرتنەوەی قەرزی کۆمپانیا: ${company.name}`,
      userId: req.user.user_id,
    });

    await client.query('COMMIT');

    logAudit(req.user.user_id, req.user.name, 'PAY_COMPANY_DEBT', 'COMPANY', compId, prevDebt, newDebt, req.ip);

    res.json({
      success: true,
      message: 'پارەی قەرزی کۆمپانیا بە سەرکەوتوویی وەرگیرا و لە قاسە تۆمارکرا',
      data: {
        new_debt: newDebt,
        paid_amount: payAmount,
      },
    });
  } catch (err) {
    await client.query('ROLLBACK');
    console.error('Error paying company debt:', err);
    res.status(500).json({ success: false, message: 'هەڵە لە وەرگرتنی پارەی قەرزی کۆمپانیا' });
  } finally {
    client.release();
  }
});

