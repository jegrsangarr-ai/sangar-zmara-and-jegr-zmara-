// Date-range Purchase & Supplier Debt Report
app.get('/api/reports/supplier-debts', authenticateToken, requireAdmin, async (req, res) => {
  try {
    const { from, to, supplier_id } = req.query;
    let suppWhere = 'is_active = 1';
    const suppParams = [];
    if (supplier_id) {
      suppParams.push(Number(supplier_id));
      suppWhere += ` AND id = $${suppParams.length}`;
    }

    const suppliersRes = await query(`SELECT * FROM suppliers WHERE ${suppWhere} ORDER BY balance_debt DESC, name ASC`, suppParams);
    const suppliers = suppliersRes.rows;

    let purWhere = '1=1';
    const purParams = [];
    if (from) {
      purParams.push(from);
      purWhere += ` AND purchase_date >= $${purParams.length}`;
    }
    if (to) {
      purParams.push(to);
      purWhere += ` AND purchase_date <= $${purParams.length}`;
    }
    if (supplier_id) {
      purParams.push(Number(supplier_id));
      purWhere += ` AND supplier_id = $${purParams.length}`;
    }

    const periodPurchasesRes = await query(`
      SELECT supplier_id, 
             COALESCE(COUNT(*), 0)::int as invoice_count,
             COALESCE(SUM(total_amount), 0)::bigint as total_purchases,
             COALESCE(SUM(paid_amount), 0)::bigint as total_paid,
             COALESCE(SUM(debt_amount), 0)::bigint as total_debt
      FROM purchases
      WHERE ${purWhere}
      GROUP BY supplier_id
    `, purParams);

    const purMap = new Map();
    for (const r of periodPurchasesRes.rows) {
      purMap.set(Number(r.supplier_id), r);
    }

    let payWhere = '1=1';
    const payParams = [];
    if (from) {
      payParams.push(from);
      payWhere += ` AND payment_date >= $${payParams.length}`;
    }
    if (to) {
      payParams.push(to);
      payWhere += ` AND payment_date <= $${payParams.length}`;
    }
    if (supplier_id) {
      payParams.push(Number(supplier_id));
      payWhere += ` AND supplier_id = $${payParams.length}`;
    }

    const periodPaymentsRes = await query(`
      SELECT supplier_id,
             COALESCE(COUNT(*), 0)::int as payment_count,
             COALESCE(SUM(amount), 0)::bigint as total_paid_to_debt
      FROM supplier_payments
      WHERE ${payWhere}
      GROUP BY supplier_id
    `, payParams);

    const payMap = new Map();
    for (const r of periodPaymentsRes.rows) {
      payMap.set(Number(r.supplier_id), r);
    }

    const reportData = suppliers.map(s => {
      const pData = purMap.get(Number(s.id)) || { invoice_count: 0, total_purchases: 0, total_paid: 0, total_debt: 0 };
      const spData = payMap.get(Number(s.id)) || { payment_count: 0, total_paid_to_debt: 0 };
      return {
        id: s.id,
        name: s.name,
        company_name: s.company_name,
        phone: s.phone,
        address: s.address,
        current_debt: Number(s.balance_debt) || 0,
        period_invoice_count: Number(pData.invoice_count) || 0,
        period_total_purchases: Number(pData.total_purchases) || 0,
        period_paid_invoices: Number(pData.total_paid) || 0,
        period_debt_invoices: Number(pData.total_debt) || 0,
        period_payments_to_debt: Number(spData.total_paid_to_debt) || 0,
      };
    });

    const totalCurrentDebt = reportData.reduce((acc, cur) => acc + cur.current_debt, 0);
    const totalPeriodPurchases = reportData.reduce((acc, cur) => acc + cur.period_total_purchases, 0);
    const totalPeriodDebt = reportData.reduce((acc, cur) => acc + cur.period_debt_invoices, 0);

    res.json({
      success: true,
      data: {
        summary: {
          total_current_debt: totalCurrentDebt,
          total_period_purchases: totalPeriodPurchases,
          total_period_debt: totalPeriodDebt,
          supplier_count: reportData.length,
        },
        suppliers: reportData
      }
    });
  } catch (err) {
    console.error('Supplier debt report error:', err);
    res.status(500).json({ success: false, message: 'هەڵە لە وەرگرتنی ڕاپۆرتی قەرزی دابینکەران' });
  }
});

// Supplier Purchase Return (Return stock to supplier with exact batch validation)
app.post('/api/purchases/:id/return', authenticateToken, requireAdmin, async (req, res) => {
  const purchaseId = req.params.id;
  const { items, reason } = req.body || {};

  if (!items || !Array.isArray(items) || items.length === 0) {
    return res.status(400).json({ success: false, message: 'هیچ کاڵایەک بۆ گەڕاندنەوە دیاری نەکراوە' });
  }

  const client = await getClient();
  try {
    await client.query('BEGIN');

    const purRes = await client.query('SELECT * FROM purchases WHERE id = $1 FOR UPDATE', [purchaseId]);
    const purchase = purRes.rows[0];
    if (!purchase) {
      await client.query('ROLLBACK');
      return res.status(404).json({ success: false, message: 'پسووڵەی کڕین نەدۆزرایەوە' });
    }

    let totalRefund = 0;

    for (const it of items) {
      const q = parseInt(it.quantity, 10) || 0;
      if (q <= 0) continue;

      // Lock the specific inventory batch created by this purchase item
      const batchRes = await client.query(
        `SELECT * FROM inventory_batches
         WHERE purchase_id = $1 AND product_id = $2
         ORDER BY id ASC FOR UPDATE`,
        [purchaseId, it.product_id]
      );

      const batch = batchRes.rows[0];
      const remainingInBatch = batch ? Number(batch.remaining_quantity) : 0;

      if (!batch || remainingInBatch < q) {
        await client.query('ROLLBACK');
        return res.status(400).json({
          success: false,
          message: `تەنها ${remainingInBatch} دانە لەم کڕینە لە کۆگا ماوە و ناتوانرێت ${q} دانە بگەڕێندرێتەوە.`,
        });
      }

      const unitCost = Number(batch.unit_cost);
      const itemRefund = q * unitCost;
      totalRefund += itemRefund;

      // Deduct from batch
      await client.query(
        `UPDATE inventory_batches
         SET remaining_quantity = remaining_quantity - $1, updated_at = NOW()
         WHERE id = $2`,
        [q, batch.id]
      );

      // Deduct from product total stock
      await client.query('UPDATE products SET quantity = GREATEST(0, quantity - $1), updated_at = NOW() WHERE id = $2', [q, it.product_id]);

      const curProdRes = await client.query('SELECT quantity FROM products WHERE id = $1', [it.product_id]);
      const curStock = curProdRes.rows[0]?.quantity || 0;

      // Log inventory movement
      await client.query(
        `INSERT INTO inventory_movements (product_id, quantity_change, stock_after, movement_type, reference_type, reference_id, user_id, notes, created_at)
         VALUES ($1, $2, $3, 'purchase_return', 'purchase', $4, $5, $6, NOW())`,
        [it.product_id, -q, curStock, purchaseId, req.user.user_id, `گەڕاندنەوە بۆ دابینکەر - پسووڵەی ${purchase.invoice_number} ${reason ? '(' + reason + ')' : ''}`]
      );
    }

    // Adjust supplier totals
    if (purchase.supplier_id && totalRefund > 0) {
      await client.query(
        `UPDATE suppliers
         SET total_purchases = GREATEST(0, total_purchases - $1),
             balance_debt = GREATEST(0, balance_debt - $1),
             updated_at = NOW()
         WHERE id = $2`,
        [totalRefund, purchase.supplier_id]
      );
    }

    await client.query('COMMIT');

    logAudit(req.user.user_id, req.user.name, 'PURCHASE_RETURN', 'PURCHASE', purchaseId, '', `گەڕاندنەوەی کڕین بە کۆی ${totalRefund} IQD`, req.ip);

    res.json({
      success: true,
      message: 'گەڕاندنەوە بۆ دابینکەر بە سەرکەوتوویی ئەنجامدرا',
      data: { total_refund: totalRefund },
    });
  } catch (err) {
    await client.query('ROLLBACK');
    res.status(500).json({ success: false, message: 'هەڵە لە گەڕاندنەوەی کاڵا بۆ دابینکەر' });
  } finally {
    client.release();
  }
});

