app.post('/api/customers/pay-debt', authenticateToken, async (req, res) => {
  const { customer_id, amount, payment_date, notes } = req.body || {};
  const payAmount = Number(amount) || 0;
  if (!customer_id || payAmount <= 0) {
    return res.status(400).json({ success: false, message: 'تکایە بڕی دروستی پارە بنووسە' });
  }

  const client = await getClient();
  try {
    await client.query('BEGIN');

    const custRes = await client.query('SELECT * FROM customers WHERE id = $1 FOR UPDATE', [customer_id]);
    const cust = custRes.rows[0];
    if (!cust) {
      await client.query('ROLLBACK');
      return res.status(404).json({ success: false, message: 'کڕیار نەدۆزرایەوە' });
    }

    const prevDebt = Number(cust.current_debt) || 0;
    if (payAmount > prevDebt) {
      await client.query('ROLLBACK');
      return res.status(400).json({
        success: false,
        message: 'بڕی پارەدان ناتوانێت لە قەرزی ماوە زیاتر بێت',
      });
    }

    const newDebt = Math.max(0, prevDebt - payAmount);
    const dateStr = payment_date || formatDate();

    await client.query(
      'UPDATE customers SET current_debt = $1, total_paid = total_paid + $2, updated_at = NOW() WHERE id = $3',
      [newDebt, payAmount, customer_id]
    );

    const payInsRes = await client.query(
      `INSERT INTO customer_debt_payments (customer_id, amount, previous_balance, new_balance, user_id, payment_date, notes, created_at)
       VALUES ($1, $2, $3, $4, $5, $6, $7, NOW())
       RETURNING id`,
      [customer_id, payAmount, prevDebt, newDebt, req.user.user_id, dateStr, notes || 'وەرگرتنەوەی قەرز']
    );
    const paymentId = payInsRes.rows[0]?.id;

    await recordCashTransaction(client, {
      cashAccountId: 1,
      transactionType: 'CUSTOMER_DEBT_PAYMENT',
      direction: 'IN',
      amount: payAmount,
      referenceType: 'customer_debt_payment',
      referenceId: paymentId,
      description: `وەرگرتنەوەی قەرزی کڕیار: ${cust.name}`,
      userId: req.user.user_id,
    });

    // Sync FIFO into customer_debts table if records exist
    let remainingToDeduct = payAmount;
    const debtsRes = await client.query(
      `SELECT id, remaining_balance FROM customer_debts WHERE customer_id = $1 AND status != 'paid' ORDER BY id ASC FOR UPDATE`,
      [customer_id]
    );
    for (const d of debtsRes.rows) {
      if (remainingToDeduct <= 0) break;
      const dRem = Number(d.remaining_balance) || 0;
      const deduct = Math.min(dRem, remainingToDeduct);
      const newDRem = dRem - deduct;
      const newStatus = newDRem === 0 ? 'paid' : 'partial';
      await client.query(
        'UPDATE customer_debts SET remaining_balance = $1, paid_amount = paid_amount + $2, status = $3, updated_at = NOW() WHERE id = $4',
        [newDRem, deduct, newStatus, d.id]
      );
      remainingToDeduct -= deduct;
    }

    await client.query('COMMIT');

    logAudit(req.user.user_id, req.user.name, 'PAY_CUSTOMER_DEBT', 'CUSTOMER', customer_id, prevDebt, newDebt, req.ip);
    res.json({
      success: true,
      message: 'پارەی قەرز بە سەرکەوتوویی وەرگیرا',
      data: {
        new_debt: newDebt,
        paid_amount: payAmount,
      },
    });
  } catch (err) {
    await client.query('ROLLBACK');
    console.error('Error paying customer debt:', err);
    res.status(500).json({ success: false, message: 'هەڵە لە وەرگرتنی پارەی قەرز' });
  } finally {
    client.release();
  }
});

