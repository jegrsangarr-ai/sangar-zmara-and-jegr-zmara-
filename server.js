// 2. Cash Transactions Log (with search and filters)
app.get('/api/cash-register/transactions', authenticateToken, async (req, res) => {
  try {
    const page = Math.max(1, parseInt(req.query.page, 10) || 1);
    const limit = Math.min(500, Math.max(1, parseInt(req.query.limit, 10) || 50));
    const offset = (page - 1) * limit;

    const date = (req.query.date || '').trim();
    const dateFrom = (req.query.date_from || '').trim();
    const dateTo = (req.query.date_to || '').trim();
    const type = (req.query.type || '').trim();
    const direction = (req.query.direction || '').trim().toUpperCase();
    const userId = req.query.user_id;
    const sessionId = req.query.session_id;
    const search = (req.query.search || '').trim();

    let where = 'WHERE ct.cash_account_id = 1';
    const params = [];
    let pIdx = 1;

    if (date) {
      where += ` AND DATE(ct.created_at AT TIME ZONE 'Asia/Baghdad') = $${pIdx}`;
      params.push(date);
      pIdx++;
    }
    if (dateFrom) {
      where += ` AND DATE(ct.created_at AT TIME ZONE 'Asia/Baghdad') >= $${pIdx}`;
      params.push(dateFrom);
      pIdx++;
    }
    if (dateTo) {
      where += ` AND DATE(ct.created_at AT TIME ZONE 'Asia/Baghdad') <= $${pIdx}`;
      params.push(dateTo);
      pIdx++;
    }
    if (sessionId) {
      where += ` AND ct.cash_session_id = $${pIdx}`;
      params.push(sessionId);
      pIdx++;
    }
    if (type) {
      if (type.toLowerCase() === 'in' || type.toLowerCase() === 'out') {
        where += ` AND ct.direction = $${pIdx}`;
        params.push(type.toUpperCase());
        pIdx++;
      } else if (type === 'sale' || type === 'sale_cash' || type === 'sale_partial_cash') {
        where += ` AND ct.transaction_type IN ('SALE_CASH', 'SALE_PARTIAL_CASH')`;
      } else if (type === 'customer_debt_payment' || type === 'company_debt_payment' || type === 'debt_payment') {
        where += ` AND ct.transaction_type IN ('CUSTOMER_DEBT_PAYMENT', 'COMPANY_DEBT_PAYMENT')`;
      } else if (type === 'purchase' || type === 'purchase_payment') {
        where += ` AND ct.transaction_type = 'PURCHASE_PAYMENT'`;
      } else if (type === 'supplier_debt_payment' || type === 'supplier_payment') {
        where += ` AND ct.transaction_type = 'SUPPLIER_PAYMENT'`;
      } else if (type === 'expense') {
        where += ` AND ct.transaction_type IN ('EXPENSE', 'EXPENSE_REVERSAL')`;
      } else if (type === 'sale_return' || type === 'refund') {
        where += ` AND ct.transaction_type = 'CUSTOMER_REFUND'`;
      } else if (type === 'manual_deposit' || type === 'deposit') {
        where += ` AND ct.transaction_type = 'CASH_DEPOSIT'`;
      } else if (type === 'manual_withdrawal' || type === 'withdrawal') {
        where += ` AND ct.transaction_type = 'CASH_WITHDRAWAL'`;
      } else {
        where += ` AND ct.transaction_type ILIKE $${pIdx}`;
        params.push(type);
        pIdx++;
      }
    }
    if (direction && (direction === 'IN' || direction === 'OUT')) {
      where += ` AND ct.direction = $${pIdx}`;
      params.push(direction);
      pIdx++;
    }
    if (userId) {
      where += ` AND ct.user_id = $${pIdx}`;
      params.push(userId);
      pIdx++;
    }
    if (search) {
      where += ` AND (ct.description ILIKE $${pIdx} OR ct.transaction_type ILIKE $${pIdx} OR ct.reference_type ILIKE $${pIdx})`;
      params.push(`%${search}%`);
      pIdx++;
    }

    const countRes = await query(`SELECT COUNT(*)::int as c FROM cash_transactions ct ${where}`, params);
    const total = countRes.rows[0]?.c || 0;

    const queryParams = [...params, limit, offset];
    const txRes = await query(`
      SELECT 
        ct.*,
        COALESCE(u.name, 'جێگر') as user_name,
        CASE 
          WHEN ct.direction = 'IN' THEN ct.balance_after - ct.amount
          ELSE ct.balance_after + ct.amount
        END as balance_before,
        CASE 
          WHEN ct.reference_type = 'sale' THEN (SELECT receipt_number FROM sales WHERE id = ct.reference_id)
          WHEN ct.reference_type = 'purchase' THEN (SELECT invoice_number FROM purchases WHERE id = ct.reference_id)
          WHEN ct.reference_type = 'return' THEN (SELECT return_number FROM returns WHERE id = ct.reference_id)
          ELSE COALESCE(ct.reference_type, 'نەقد')
        END as reference_number,
        LOWER(ct.transaction_type) as source,
        ct.description as notes
      FROM cash_transactions ct
      LEFT JOIN users u ON ct.user_id = u.id
      ${where}
      ORDER BY ct.created_at DESC, ct.id DESC
      LIMIT $${pIdx} OFFSET $${pIdx + 1}
    `, queryParams);

    res.json({
      success: true,
      data: txRes.rows,
      total,
      page,
      limit,
    });
  } catch (err) {
    console.error('Cash transactions error:', err);
    res.status(500).json({ success: false, message: 'هەڵە لە وەرگرتنی جووڵەی قاسە' });
  }
});

