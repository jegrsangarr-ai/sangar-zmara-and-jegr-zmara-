async function syncHistoricalCashTransactions(existingClient = null) {
  const client = existingClient || await getClient();
  const shouldRelease = !existingClient;
  let backfilledCount = 0;

  try {
    if (shouldRelease) await client.query('BEGIN');

    // 1. Sales cash payments
    const salesRes = await client.query(`
      SELECT s.id, s.receipt_number, s.paid_amount, s.debt_amount, s.user_id, s.created_at
      FROM sales s
      WHERE s.paid_amount > 0
        AND NOT EXISTS (
          SELECT 1 FROM cash_transactions ct 
          WHERE ct.reference_type = 'sale' AND ct.reference_id = s.id
        )
      ORDER BY s.created_at ASC, s.id ASC
    `);

    for (const s of salesRes.rows) {
      const amt = Number(s.paid_amount);
      const type = Number(s.debt_amount) > 0 ? 'SALE_PARTIAL_CASH' : 'SALE_CASH';
      await client.query(`
        INSERT INTO cash_transactions (
          cash_account_id, transaction_type, direction, amount, balance_after,
          reference_type, reference_id, description, user_id, backfilled, created_at
        ) VALUES (1, $1, 'IN', $2, 0, 'sale', $3, $4, $5, TRUE, $6)
      `, [type, amt, s.id, `فرۆشتنی پسووڵەی ${s.receipt_number} (پێشینە)`, s.user_id, s.created_at]);
      backfilledCount++;
    }

    // 2. Customer debt payments
    const cDebtRes = await client.query(`
      SELECT cdp.id, cdp.customer_id, cdp.amount, cdp.user_id, cdp.created_at, cdp.notes, c.name as customer_name
      FROM customer_debt_payments cdp
      LEFT JOIN customers c ON cdp.customer_id = c.id
      WHERE cdp.amount > 0
        AND NOT EXISTS (
          SELECT 1 FROM cash_transactions ct 
          WHERE ct.reference_type = 'customer_debt_payment' AND ct.reference_id = cdp.id
        )
      ORDER BY cdp.created_at ASC, cdp.id ASC
    `);

    for (const d of cDebtRes.rows) {
      const amt = Number(d.amount);
      await client.query(`
        INSERT INTO cash_transactions (
          cash_account_id, transaction_type, direction, amount, balance_after,
          reference_type, reference_id, description, user_id, backfilled, created_at
        ) VALUES (1, 'CUSTOMER_DEBT_PAYMENT', 'IN', $1, 0, 'customer_debt_payment', $2, $3, $4, TRUE, $5)
      `, [amt, d.id, d.notes || `وەرگرتنەوەی قەرزی کڕیار: ${d.customer_name || 'کڕیار'}`, d.user_id, d.created_at]);
      backfilledCount++;
    }

    // 3. Company debt payments
    const compDebtRes = await client.query(`
      SELECT cdp.id, cdp.company_id, cdp.amount, COALESCE(cdp.received_by, cdp.user_id) as received_by, cdp.created_at, cdp.notes, comp.name as comp_name
      FROM company_debt_payments cdp
      LEFT JOIN companies comp ON cdp.company_id = comp.id
      WHERE cdp.amount > 0
        AND NOT EXISTS (
          SELECT 1 FROM cash_transactions ct 
          WHERE ct.reference_type = 'company_debt_payment' AND ct.reference_id = cdp.id
        )
      ORDER BY cdp.created_at ASC, cdp.id ASC
    `);

    for (const cd of compDebtRes.rows) {
      const amt = Number(cd.amount);
      await client.query(`
        INSERT INTO cash_transactions (
          cash_account_id, transaction_type, direction, amount, balance_after,
          reference_type, reference_id, description, user_id, backfilled, created_at
        ) VALUES (1, 'COMPANY_DEBT_PAYMENT', 'IN', $1, 0, 'company_debt_payment', $2, $3, $4, TRUE, $5)
      `, [amt, cd.id, cd.notes || `وەرگرتنەوەی قەرزی کۆمپانیا: ${cd.comp_name || 'کۆمپانیا'}`, cd.received_by, cd.created_at]);
      backfilledCount++;
    }

    // 4. Purchases cash paid
    const purRes = await client.query(`
      SELECT p.id, p.invoice_number, p.paid_amount, p.user_id, p.created_at
      FROM purchases p
      WHERE p.paid_amount > 0
        AND NOT EXISTS (
          SELECT 1 FROM cash_transactions ct 
          WHERE ct.reference_type = 'purchase' AND ct.reference_id = p.id
        )
      ORDER BY p.created_at ASC, p.id ASC
    `);

    for (const p of purRes.rows) {
      const amt = Number(p.paid_amount);
      await client.query(`
        INSERT INTO cash_transactions (
          cash_account_id, transaction_type, direction, amount, balance_after,
          reference_type, reference_id, description, user_id, backfilled, created_at
        ) VALUES (1, 'PURCHASE_PAYMENT', 'OUT', $1, 0, 'purchase', $2, $3, $4, TRUE, $5)
      `, [amt, p.id, `پارەدانی وەسڵی کڕین ${p.invoice_number || p.id} (پێشینە)`, p.user_id, p.created_at]);
      backfilledCount++;
    }

    // 5. Supplier payments
    const sPayRes = await client.query(`
      SELECT sp.id, sp.supplier_id, sp.amount, sp.user_id, sp.created_at, sp.notes, s.name as supp_name
      FROM supplier_payments sp
      LEFT JOIN suppliers s ON sp.supplier_id = s.id
      WHERE sp.amount > 0
        AND NOT EXISTS (
          SELECT 1 FROM cash_transactions ct 
          WHERE ct.reference_type = 'supplier_payment' AND ct.reference_id = sp.id
        )
      ORDER BY sp.created_at ASC, sp.id ASC
    `);

    for (const sp of sPayRes.rows) {
      const amt = Number(sp.amount);
      await client.query(`
        INSERT INTO cash_transactions (
          cash_account_id, transaction_type, direction, amount, balance_after,
          reference_type, reference_id, description, user_id, backfilled, created_at
        ) VALUES (1, 'SUPPLIER_PAYMENT', 'OUT', $1, 0, 'supplier_payment', $2, $3, $4, TRUE, $5)
      `, [amt, sp.id, sp.notes || `دانەوەی قەرزی دابینکەر: ${sp.supp_name || 'دابینکەر'}`, sp.user_id, sp.created_at]);
      backfilledCount++;
    }

    // 6. Expenses
    const expRes = await client.query(`
      SELECT e.id, e.amount, e.description, e.user_id, e.created_at
      FROM expenses e
      WHERE e.amount > 0
        AND NOT EXISTS (
          SELECT 1 FROM cash_transactions ct 
          WHERE ct.reference_type = 'expense' AND ct.reference_id = e.id
        )
      ORDER BY e.created_at ASC, e.id ASC
    `);

    for (const e of expRes.rows) {
      const amt = Number(e.amount);
      await client.query(`
        INSERT INTO cash_transactions (
          cash_account_id, transaction_type, direction, amount, balance_after,
          reference_type, reference_id, description, user_id, backfilled, created_at
        ) VALUES (1, 'EXPENSE', 'OUT', $1, 0, 'expense', $2, $3, $4, TRUE, $5)
      `, [amt, e.id, e.description || 'تۆماری خەرجی (پێشینە)', e.user_id, e.created_at]);
      backfilledCount++;
    }

    // 7. Returns refund
    const retRes = await client.query(`
      SELECT r.id, r.return_number, r.total_refund, r.user_id, r.created_at
      FROM returns r
      WHERE r.total_refund > 0
        AND NOT EXISTS (
          SELECT 1 FROM cash_transactions ct 
          WHERE ct.reference_type = 'return' AND ct.reference_id = r.id
        )
      ORDER BY r.created_at ASC, r.id ASC
    `);

    for (const r of retRes.rows) {
      const amt = Number(r.total_refund);
      await client.query(`
        INSERT INTO cash_transactions (
          cash_account_id, transaction_type, direction, amount, balance_after,
          reference_type, reference_id, description, user_id, backfilled, created_at
        ) VALUES (1, 'CUSTOMER_REFUND', 'OUT', $1, 0, 'return', $2, $3, $4, TRUE, $5)
      `, [amt, r.id, `گەڕاندنەوەی پارەی فرۆشتن ${r.return_number || r.id} (پێشینە)`, r.user_id, r.created_at]);
      backfilledCount++;
    }

    // Link any active open session to unlinked cash transactions created during that session
    const openSessionRes = await client.query(`
      SELECT id, opened_at, opening_balance FROM cash_sessions
      WHERE cash_account_id = 1 AND status = 'OPEN'
      ORDER BY id DESC LIMIT 1
    `);
    if (openSessionRes.rows.length > 0) {
      const openSession = openSessionRes.rows[0];
      await client.query(`
        UPDATE cash_transactions
        SET cash_session_id = $1
        WHERE cash_account_id = 1
          AND cash_session_id IS NULL
          AND created_at >= $2
      `, [openSession.id, openSession.opened_at]);
    }

    // Recalculate running balance_after for all cash_transactions
    const allTxRes = await client.query(`
      SELECT id, direction, amount FROM cash_transactions
      WHERE cash_account_id = 1
      ORDER BY created_at ASC, id ASC
      FOR UPDATE
    `);

    const accRes = await client.query('SELECT opening_balance FROM cash_accounts WHERE id = 1');
    let running = Number(accRes.rows[0]?.opening_balance || 0);

    for (const tx of allTxRes.rows) {
      const amt = Number(tx.amount);
      if (tx.direction === 'IN') {
        running += amt;
      } else {
        running -= amt;
      }
      await client.query('UPDATE cash_transactions SET balance_after = $1 WHERE id = $2', [running, tx.id]);
    }

    await client.query('UPDATE cash_accounts SET current_balance = $1, updated_at = NOW() WHERE id = 1', [running]);

    if (shouldRelease) await client.query('COMMIT');
    console.log(`✅ Cash transactions synced successfully. Added: ${backfilledCount}, New Cash Balance: ${running} IQD`);
    return { success: true, count: backfilledCount, balance: running };
  } catch (err) {
    if (shouldRelease) await client.query('ROLLBACK');
    console.warn('⚠️ Cash synchronization failed:', err.message);
    throw err;
  } finally {
    if (shouldRelease) client.release();
  }
}

