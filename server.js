    await query(`ALTER TABLE cash_transactions ADD COLUMN IF NOT EXISTS backfilled BOOLEAN DEFAULT FALSE`).catch(() => {});
    await query(`ALTER TABLE cash_transactions ADD COLUMN IF NOT EXISTS is_reversal SMALLINT DEFAULT 0`).catch(() => {});
    await query(`ALTER TABLE cash_transactions ADD COLUMN IF NOT EXISTS reversal_of_id BIGINT`).catch(() => {});

