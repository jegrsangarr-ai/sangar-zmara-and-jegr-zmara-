const handleCloseSession = async (req, res, sessionIdParam = null) => {
  const { closing_balance, closing_balance_actual, notes } = req.body || {};
  const actualAmt = Number(closing_balance_actual !== undefined ? closing_balance_actual : closing_balance) || 0;

  const client = await getClient();
  try {
    await client.query('BEGIN');

    let sessionQuery = "SELECT * FROM cash_sessions WHERE cash_account_id = 1 AND status = 'OPEN'";
    const queryParams = [];
    if (sessionIdParam) {
      sessionQuery += " AND id = $1";
      queryParams.push(sessionIdParam);
    }
    sessionQuery += " ORDER BY id DESC LIMIT 1 FOR UPDATE";

    const openRes = await client.query(sessionQuery, queryParams);
    const session = openRes.rows[0];
    if (!session) {
      await client.query('ROLLBACK');
      return res.status(400).json({ success: false, message: 'هیچ سیشنێکی کراوەی قاسە نەدۆزرایەوە بۆ داخستن' });
    }

    const txsRes = await client.query(`
      SELECT 
        COALESCE(SUM(CASE WHEN direction = 'IN' THEN amount ELSE 0 END), 0)::bigint as total_in,
        COALESCE(SUM(CASE WHEN direction = 'OUT' THEN amount ELSE 0 END), 0)::bigint as total_out
      FROM cash_transactions
      WHERE cash_account_id = 1 
        AND (cash_session_id = $1 OR (created_at >= $2 AND cash_session_id IS NULL))
    `, [session.id, session.opened_at]);

    const sessionIn = Number(txsRes.rows[0]?.total_in || 0);
    const sessionOut = Number(txsRes.rows[0]?.total_out || 0);
    const expected = Number(session.opening_balance || 0) + sessionIn - sessionOut;
    const diff = actualAmt - expected;

    const updateRes = await client.query(`
      UPDATE cash_sessions
      SET closing_balance_expected = $1,
          closing_balance_actual = $2,
          difference = $3,
          status = 'CLOSED',
          closed_at = NOW(),
          notes = COALESCE($4, notes)
      WHERE id = $5
      RETURNING *
    `, [expected, actualAmt, diff, notes || '', session.id]);

    await client.query(`UPDATE cash_accounts SET current_balance = $1, updated_at = NOW() WHERE id = 1`, [actualAmt]);

    await client.query('COMMIT');
    res.json({
      success: true,
      data: updateRes.rows[0],
      message: `قاسە بە سەرکەوتوویی داخرا. ${diff === 0 ? 'ژماردن تەواو هاوتا بوو ✓' : diff > 0 ? `زیادەی قاسە: ${diff.toLocaleString()} د.ع` : `کورتهێنانی قاسە: ${Math.abs(diff).toLocaleString()} د.ع`}`,
    });
  } catch (err) {
    await client.query('ROLLBACK');
    console.error('Session close error:', err);
    res.status(500).json({ success: false, message: 'هەڵە لە داخستنی سیشنی قاسە' });
  } finally {
    client.release();
  }
};

