async function fetchDashboardSummary(user) {
  const today = getErbilDateString();
  const firstOfMonth = `${today.slice(0, 7)}-01`;
  const lastOfMonth = `${today.slice(0, 7)}-31`;
  const last7Days = getLast7Days();
  const startDate7 = last7Days[0];
  const endDate7 = last7Days[last7Days.length - 1];

  // 1. Today's sales and gross profit
  const todaySalesRes = await query(
    `SELECT
       COALESCE(SUM(total_amount), 0)::bigint AS today_sales,
       COALESCE(SUM(gross_profit), 0)::bigint AS today_gross_profit,
       COALESCE(SUM(total_cost), 0)::bigint AS today_total_cost,
       COUNT(*)::int AS today_transactions
     FROM sales
     WHERE sale_date = $1 AND status NOT IN ('cancelled', 'deleted')`,
    [today]
  );

  // 2. Month's sales and gross profit
  const monthSalesRes = await query(
    `SELECT
       COALESCE(SUM(total_amount), 0)::bigint AS month_sales,
       COALESCE(SUM(gross_profit), 0)::bigint AS month_gross_profit,
       COALESCE(SUM(total_cost), 0)::bigint AS month_total_cost,
       COUNT(*)::int AS month_transactions
     FROM sales
     WHERE sale_date >= $1 AND sale_date <= $2 AND status NOT IN ('cancelled', 'deleted')`,
    [firstOfMonth, lastOfMonth]
  );

  // 3. Today's expenses
  const todayExpRes = await query(
    `SELECT COALESCE(SUM(amount), 0)::bigint AS today_expenses
     FROM expenses
     WHERE expense_date = $1`,
    [today]
  );

  // 4. Month's expenses
  const monthExpRes = await query(
    `SELECT COALESCE(SUM(amount), 0)::bigint AS month_expenses
     FROM expenses
     WHERE expense_date >= $1 AND expense_date <= $2`,
    [firstOfMonth, lastOfMonth]
  );

  // 5. Customer debt (actual remaining customer debt from active customers)
  const custDebtRes = await query(
    `SELECT GREATEST(0, COALESCE(SUM(current_debt), 0))::bigint AS total_customer_debt
     FROM customers
     WHERE is_active = 1 AND current_debt > 0`
  );

  // 5b. Company debt (actual remaining company debt from active companies)
  const compDebtRes = await query(
    `SELECT GREATEST(0, COALESCE(SUM(current_debt), 0))::bigint AS total_company_debt
     FROM companies
     WHERE is_active = 1 AND current_debt > 0`
  );

  // 6. Supplier debt (actual balance debt to active suppliers)
  const suppDebtRes = await query(
    `SELECT GREATEST(0, COALESCE(SUM(balance_debt), 0))::bigint AS total_supplier_debt
     FROM suppliers
     WHERE is_active = 1 AND balance_debt > 0`
  );

  // 7. Low stock & out of stock counts
  const stockCountsRes = await query(
    `SELECT
       COALESCE(SUM(CASE WHEN quantity <= min_stock_level AND quantity > 0 THEN 1 ELSE 0 END), 0)::int AS low_stock_count,
       COALESCE(SUM(CASE WHEN quantity <= 0 THEN 1 ELSE 0 END), 0)::int AS out_of_stock_count
     FROM products
     WHERE is_active = 1`
  );

  // 8. 7-Day sales trend (guaranteed 7 days array with 0 for missing days)
  const chartRes = await query(
    `SELECT
       sale_date::text AS date,
       COALESCE(SUM(total_amount), 0)::bigint AS total
     FROM sales
     WHERE sale_date >= $1 AND sale_date <= $2 AND status NOT IN ('cancelled', 'deleted')
     GROUP BY sale_date
     ORDER BY sale_date ASC`,
    [startDate7, endDate7]
  );

  const salesByDate = {};
  for (const row of chartRes.rows) {
    // Standardize date string format YYYY-MM-DD
    const dStr = typeof row.date === 'string' ? row.date.slice(0, 10) : formatDate(row.date);
    salesByDate[dStr] = Number(row.total || 0);
  }

  const chartData = last7Days.map((dStr) => ({
    date: dStr,
    total: salesByDate[dStr] || 0,
    sales: salesByDate[dStr] || 0,
  }));

  // 9. Best-selling products (from real sale_items)
  const topProductsRes = await query(
    `SELECT
       si.product_id,
       si.product_name,
       COALESCE(si.part_number, '') AS part_number,
       COALESCE(SUM(si.quantity - si.returned_quantity), 0)::int AS total_qty,
       COALESCE(SUM(si.total_price), 0)::bigint AS total_revenue
     FROM sale_items si
     JOIN sales s ON si.sale_id = s.id
     WHERE s.status NOT IN ('cancelled', 'deleted')
     GROUP BY si.product_id, si.product_name, si.part_number
     HAVING SUM(si.quantity - si.returned_quantity) > 0
     ORDER BY total_qty DESC, total_revenue DESC
     LIMIT 6`
  );

  // 10. Low stock products list
  const lowStockItemsRes = await query(
    `SELECT
       p.id,
       p.name,
       COALESCE(p.truck_brand, 'گشتی') AS truck_brand,
       COALESCE(p.truck_model, '') AS truck_model,
       COALESCE(p.part_number, '-') AS part_number,
       p.quantity,
       p.min_stock_level,
       p.selling_price
     FROM products p
     WHERE p.is_active = 1 AND p.quantity <= p.min_stock_level
     ORDER BY p.quantity ASC, p.id DESC
     LIMIT 10`
  );

  // 11. Recent sales
  const recentSalesRes = await query(
    `SELECT
       s.id,
       s.receipt_number,
       s.total_amount,
       s.paid_amount,
       s.debt_amount,
       s.payment_type,
       s.status,
       s.sale_date,
       s.sale_time,
       COALESCE(c.name, 'کڕیاری دەستبەجێ') AS customer_name,
       COALESCE(u.name, 'کاشێر') AS user_name
     FROM sales s
     LEFT JOIN customers c ON s.customer_id = c.id
     LEFT JOIN users u ON s.user_id = u.id
     WHERE s.status NOT IN ('cancelled', 'deleted')
     ORDER BY s.id DESC
     LIMIT 6`
  );

  const tSales = Number(todaySalesRes.rows[0]?.today_sales || 0);
  const tGrossProfit = Number(todaySalesRes.rows[0]?.today_gross_profit || 0);
  const tTx = Number(todaySalesRes.rows[0]?.today_transactions || 0);
  const tExpenses = Number(todayExpRes.rows[0]?.today_expenses || 0);
  const tNetProfit = tGrossProfit - tExpenses;

  const mSales = Number(monthSalesRes.rows[0]?.month_sales || 0);
  const mGrossProfit = Number(monthSalesRes.rows[0]?.month_gross_profit || 0);
  const mTx = Number(monthSalesRes.rows[0]?.month_transactions || 0);
  const mExpenses = Number(monthExpRes.rows[0]?.month_expenses || 0);
  const mNetProfit = mGrossProfit - mExpenses;

  const custDebt = Number(custDebtRes.rows[0]?.total_customer_debt || 0);
  const compDebt = Number(compDebtRes.rows[0]?.total_company_debt || 0);
  const suppDebt = Number(suppDebtRes.rows[0]?.total_supplier_debt || 0);
  const lowCount = Number(stockCountsRes.rows[0]?.low_stock_count || 0);
  const outCount = Number(stockCountsRes.rows[0]?.out_of_stock_count || 0);

  const isAdminUser = user && (user.role === 'admin' || user.role_name === 'admin');

  return {
    // Canonical camelCase
    todaySales: tSales,
    todayGrossProfit: isAdminUser ? tGrossProfit : 0,
    todayExpenses: tExpenses,
    todayNetProfit: isAdminUser ? tNetProfit : 0,
    todayTransactions: tTx,
    monthSales: mSales,
    monthGrossProfit: isAdminUser ? mGrossProfit : 0,
    monthExpenses: mExpenses,
    monthNetProfit: isAdminUser ? mNetProfit : 0,
    customerDebt: custDebt,
    companyDebt: compDebt,
    supplierDebt: isAdminUser ? suppDebt : 0,
    lowStockCount: lowCount,
    outOfStockCount: outCount,
    chartData,
    topProducts: topProductsRes.rows,
    lowStockItems: lowStockItemsRes.rows,
    recentSales: recentSalesRes.rows,

    // Snake_case aliases for 100% compatibility
    today_sales: tSales,
    today_gross_profit: isAdminUser ? tGrossProfit : 0,
    today_expenses: tExpenses,
    today_net_profit: isAdminUser ? tNetProfit : 0,
    today_transactions: tTx,
    today_sales_count: tTx,
    monthly_sales: mSales,
    month_sales: mSales,
    month_gross_profit: isAdminUser ? mGrossProfit : 0,
    month_expenses: mExpenses,
    month_net_profit: isAdminUser ? mNetProfit : 0,
    total_customer_debt: custDebt,
    customer_debt: custDebt,
    total_company_debt: compDebt,
    company_debt: compDebt,
    total_supplier_debt: isAdminUser ? suppDebt : 0,
    supplier_debt: isAdminUser ? suppDebt : 0,
    low_stock_count: lowCount,
    out_of_stock_count: outCount,
    chart_data: chartData,
    sales_trend: chartData,
    top_products: topProductsRes.rows,
    low_stock_items: lowStockItemsRes.rows,
    recent_sales: recentSalesRes.rows,

    // Nested object aliases
    today: {
      sales: tSales,
      total_sales: tSales,
      gross_profit: isAdminUser ? tGrossProfit : 0,
      net_profit: isAdminUser ? tNetProfit : 0,
      expenses: tExpenses,
      sales_count: tTx,
      transactions_count: tTx,
    },
    month: {
      sales: mSales,
      total_sales: mSales,
      gross_profit: isAdminUser ? mGrossProfit : 0,
      net_profit: isAdminUser ? mNetProfit : 0,
      expenses: mExpenses,
      transactions_count: mTx,
    },
    debts: {
      customer_debts: custDebt,
      supplier_debts: isAdminUser ? suppDebt : 0,
    },
    inventory: {
      low_stock_count: lowCount,
      out_of_stock: outCount,
    },
    server_time: getErbilTime().toISOString(),
    timezone: 'Asia/Baghdad',
  };
}

