async function bootstrapFifoSchema() {
  try {
    await query(`
      CREATE TABLE IF NOT EXISTS inventory_batches (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
        purchase_id BIGINT REFERENCES purchases(id) ON DELETE SET NULL,
        purchase_item_id BIGINT REFERENCES purchase_items(id) ON DELETE SET NULL,
        supplier_id BIGINT REFERENCES suppliers(id) ON DELETE SET NULL,
        batch_type VARCHAR(50) NOT NULL DEFAULT 'PURCHASE',
        batch_number VARCHAR(100),
        original_quantity INT NOT NULL,
        remaining_quantity INT NOT NULL,
        unit_cost BIGINT NOT NULL DEFAULT 0,
        purchase_date DATE NOT NULL DEFAULT CURRENT_DATE,
        notes TEXT,
        created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
      )
    `);

    await query(`
      CREATE TABLE IF NOT EXISTS sale_item_cost_allocations (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        sale_id BIGINT NOT NULL REFERENCES sales(id) ON DELETE CASCADE,
        sale_item_id BIGINT NOT NULL REFERENCES sale_items(id) ON DELETE CASCADE,
        product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
        batch_id BIGINT NOT NULL REFERENCES inventory_batches(id) ON DELETE RESTRICT,
        quantity INT NOT NULL,
        unit_cost BIGINT NOT NULL DEFAULT 0,
        total_cost BIGINT NOT NULL DEFAULT 0,
        created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
      )
    `);

    await query(`
      CREATE TABLE IF NOT EXISTS sale_return_cost_allocations (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        return_id BIGINT NOT NULL REFERENCES returns(id) ON DELETE CASCADE,
        return_item_id BIGINT NOT NULL REFERENCES return_items(id) ON DELETE CASCADE,
        sale_item_cost_allocation_id BIGINT REFERENCES sale_item_cost_allocations(id) ON DELETE SET NULL,
        batch_id BIGINT NOT NULL REFERENCES inventory_batches(id) ON DELETE RESTRICT,
        quantity INT NOT NULL,
        unit_cost BIGINT NOT NULL DEFAULT 0,
        total_cost BIGINT NOT NULL DEFAULT 0,
        created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
      )
    `);

    await query(`CREATE INDEX IF NOT EXISTS idx_inv_batches_prod_rem ON inventory_batches (product_id, remaining_quantity)`).catch(() => {});
    await query(`CREATE INDEX IF NOT EXISTS idx_inv_batches_prod_fifo ON inventory_batches (product_id, purchase_date ASC, id ASC)`).catch(() => {});
    await query(`CREATE INDEX IF NOT EXISTS idx_cost_alloc_sale ON sale_item_cost_allocations (sale_id)`).catch(() => {});
    await query(`CREATE INDEX IF NOT EXISTS idx_cost_alloc_sale_item ON sale_item_cost_allocations (sale_item_id)`).catch(() => {});
    await query(`CREATE INDEX IF NOT EXISTS idx_cost_alloc_batch ON sale_item_cost_allocations (batch_id)`).catch(() => {});

    // Idempotent initial opening balance batch seeding for existing stock
    const unbatched = await query(`
      SELECT p.id, p.quantity, p.purchase_price, p.supplier_id
      FROM products p
      WHERE p.quantity > 0
        AND NOT EXISTS (SELECT 1 FROM inventory_batches b WHERE b.product_id = p.id)
    `);

    if (unbatched.rows && unbatched.rows.length > 0) {
      for (const p of unbatched.rows) {
        await query(`
          INSERT INTO inventory_batches (
            product_id, supplier_id, batch_type, batch_number,
            original_quantity, remaining_quantity, unit_cost, purchase_date, notes
          ) VALUES ($1, $2, 'OPENING_BALANCE', $3, $4, $4, $5, CURRENT_DATE, 'مەخزەنی سەرەتایی کاتی کاراکردنی FIFO')
        `, [p.id, p.supplier_id || null, `INIT-${p.id}`, p.quantity, p.purchase_price || 0]);
      }
      console.log(`✅ Seeded ${unbatched.rows.length} opening inventory batches for FIFO tracking`);
    }
  } catch (err) {
    console.warn('⚠️ FIFO bootstrap notice:', err.message);
  }
}

