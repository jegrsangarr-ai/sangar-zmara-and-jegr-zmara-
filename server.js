/// Auth Middleware
async function authenticateToken(req, res, next) {
  const authHeader = req.headers['authorization'];
  const token = authHeader && authHeader.split(' ')[1];

  if (!token) {
    return res.status(401).json({ success: false, message: 'تکایە سەرەتا بچۆ ژوورەوە' });
  }

  try {
    let decoded;
    try {
      decoded = jwt.verify(token, JWT_SECRET);
    } catch (jwtErr) {
      return res.status(401).json({ success: false, message: 'تۆکنەکەت بەسەرچووە یان نادروستە' });
    }

    const userId = decoded.id || decoded.user_id;
    const userEmail = (decoded.email || decoded.username || '').trim().toLowerCase();

    // Fetch user directly from local SQLite database
    const userRes = await query(
      `SELECT u.id, u.name, u.email, u.username, u.role_id, u.is_active, u.phone,
              r.name as role_name, r.display_name as role_display_name
       FROM users u
       JOIN roles r ON u.role_id = r.id
       WHERE u.id = $1 OR LOWER(TRIM(u.email)) = $2 OR LOWER(TRIM(u.username)) = $2
       LIMIT 1`,
      [userId || 0, userEmail]
    );

    const user = userRes.rows[0];
    if (!user) {
      return res.status(401).json({ success: false, message: 'بەکارهێنەر نەدۆزرایەوە' });
    }

    if (user.is_active === 0 || user.is_active === '0' || user.is_active === false) {
      return res.status(403).json({
        success: false,
        message: 'هەژمارەکەت ناچالاک کراوە',
        code: 'ACCOUNT_INACTIVE',
      });
    }

    req.user = {
      id: user.id,
      user_id: user.id,
      email: user.email,
      username: user.username || user.email.split('@')[0],
      name: user.name,
      full_name: user.name,
      role: user.role_name,
      role_name: user.role_name,
      role_display_name: user.role_display_name,
      role_id: user.role_id,
      is_active: user.is_active,
      phone: user.phone || '',
    };

    next();
  } catch (err) {
    console.error('Auth verification error:', err);
    return res.status(401).json({ success: false, message: 'هەڵە لە دڵنیابوونەوە لە ناسنامە' });
  }
}

