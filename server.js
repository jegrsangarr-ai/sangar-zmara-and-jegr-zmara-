// Returns (Sales Return / ئیسترجاع)
app.post('/api/returns', authenticateToken, async (req, res) => {
  let { sale_id, reason, notes, items, sale_item_id, product_id, quantity } = req.body || {};
  if (!sale_id) return res.status(400).json({ success: false, message: 'تکایە پسووڵەی فرۆشتن هەڵبژێرە' });

  if ((!items || !items.length) && (sale_item_id || product_id) && quantity) {
    items = [{ sale_item_id, product_id, quantity }];
  }

  if (!items || !items.length) return res.status(400).json({ success: false, message: 'هیچ کاڵایەکت بۆ گەڕانەوە دیاری نەکردووە' });

  const client = await getClient();
  try {
    await client.query('BEGIN');

    const saleRes = await client.query('SELECT * FROM sales WHERE id = $1 FOR UPDATE', [sale_id]);
    const sale = saleRes.rows[0];
    if (!sale) {
      await client.query('ROLLBACK');
      return res.status(404).json({ success: false, message: 'پسووڵەی فرۆشتنی سەرەکی نەدۆزرایەوە' });
    }

    let totalRefund = 0;
    const verified = [];

    for (const it of items) {
      const q = parseInt(it.quantity, 10) || 0;
      if (q <= 0) {
        await client.query('ROLLBACK');
        return res.status(400).json({ success: false, message: 'بڕی گەڕاندنەوە نادروستە (دەبێت لە 0 زیاتر بێت)' });
      }

      let saleItem = null;
      if (it.sale_item_id) {
        const siRes = await client.query('SELECT * FROM sale_items WHERE id = $1 AND sale_id = $2 FOR UPDATE', [it.sale_item_id, sale_id]);
        saleItem = siRes.rows[0];
      } else if (it.product_id) {
        const siRes = await client.query('SELECT * FROM sale_items WHERE product_id = $1 AND sale_id = $2 ORDER BY id ASC LIMIT 1 FOR UPDATE', [it.product_id, sale_id]);
        saleItem = siRes.rows[0];
      }

      if (!saleItem) {
        await client.query('ROLLBACK');
        return res.status(400).json({ success: false, message: 'کاڵای دیاریکراو لەم پسووڵەیەدا نەدۆزرایەوە' });
      }

      const available = Math.max(0, Number(saleItem.quantity) - Number(saleItem.returned_quantity));
      if (available <= 0) {
        await client.query('ROLLBACK');
        return res.status(400).json({ success: false, message: `کاڵای (${saleItem.product_name}) پێشتر بە تەواوی گەڕێندراوەتەوە` });
      }
      if (q > available) {
        await client.query('ROLLBACK');
        return res.status(400).json({ success: false, message: `بڕی داواکراو بۆ گەڕاندنەوەی (${saleItem.product_name}) لە بڕی ماوە زیاترە` });
      }

      const unitRefund = Number(saleItem.quantity) > 0 ? Math.round(Number(saleItem.total_price) / Number(saleItem.quantity)) : Number(saleItem.unit_price);
      const itemRefund = unitRefund * q;
      totalRefund += itemRefund;

      verified.push({
        sale_item_id: saleItem.id,
        product_id: saleItem.product_id,
        product_name: saleItem.product_name,
        quantity: q,
        unit_price: Number(saleItem.unit_price),
        unit_cost: Number(saleItem.unit_cost),
        refund_amount: itemRefund,
      });
    }

    const now = getErbilTime();
    const dateStr = formatDate(now);

    const maxRetRes = await client.query('SELECT COALESCE(MAX(id), 0)::bigint as max_id FROM returns');
    const nextRetId = Number(maxRetRes.rows[0]?.max_id || 0) + 1;
    const returnNumber = `RET-${now.getFullYear()}-${String(nextRetId).padStart(5, '0')}`;
    const fullReason = notes ? `${reason || 'NOT_WORKING'} (${notes})` : reason || 'NOT_WORKING';

    const retInsertRes = await client.query(
      `INSERT INTO returns (return_number, sale_id, customer_id, user_id, total_refund, return_date, reason, created_at)
       VALUES ($1, $2, $3, $4, $5, $6, $7, NOW())
       RETURNING *`,
      [returnNumber, sale_id, sale.customer_id || null, req.user.user_id, totalRefund, dateStr, fullReason]
    );

    const returnId = retInsertRes.rows[0].id;

    for (const it of verified) {
      const riRes = await client.query(
        `INSERT INTO return_items (return_id, sale_item_id, product_id, quantity, unit_price, unit_cost, refund_amount, created_at)
         VALUES ($1, $2, $3, $4, $5, $6, $7, NOW())
         RETURNING id`,
        [returnId, it.sale_item_id, it.product_id, it.quantity, it.unit_price, it.unit_cost, it.refund_amount]
      );

      const returnItemId = riRes.rows[0]?.id;

      // Restore batch stock for FIFO tracking
      let qtyToRestore = it.quantity;
      const allocsRes = await client.query(
        'SELECT * FROM sale_item_cost_allocations WHERE sale_item_id = $1 ORDER BY id DESC FOR UPDATE',
        [it.sale_item_id]
      );
      const allocs = allocsRes.rows || [];

      for (const alloc of allocs) {
        if (qtyToRestore <= 0) break;
        const allocQty = Number(alloc.quantity);
        const restoreNow = Math.min(qtyToRestore, allocQty);

        if (alloc.batch_id) {
          await client.query(
            `UPDATE inventory_batches
             SET remaining_quantity = LEAST(original_quantity, remaining_quantity + $1), updated_at = NOW()
             WHERE id = $2`,
            [restoreNow, alloc.batch_id]
          );

          if (returnItemId) {
            await client.query(
              `INSERT INTO sale_return_cost_allocations (
                return_id, return_item_id, sale_item_cost_allocation_id, batch_id, quantity, unit_cost, total_cost, created_at
              ) VALUES ($1, $2, $3, $4, $5, $6, $7, NOW())`,
              [returnId, returnItemId, alloc.id, alloc.batch_id, restoreNow, Number(alloc.unit_cost), restoreNow * Number(alloc.unit_cost)]
            );
          }
        }
        qtyToRestore -= restoreNow;
      }

      if (qtyToRestore > 0) {
        const retBatchRes = await client.query(
          `INSERT INTO inventory_batches (
            product_id, batch_type, batch_number, original_quantity, remaining_quantity, unit_cost, purchase_date, notes, created_at, updated_at
          ) VALUES ($1, 'RETURN', $2, $3, $3, $4, CURRENT_DATE, 'گەڕاندنەوەی فرۆشتن', NOW(), NOW())
          RETURNING id`,
          [it.product_id, `RET-BATCH-${returnId}-${it.product_id}`, qtyToRestore, it.unit_cost]
        );
        const retBatchId = retBatchRes.rows[0]?.id;
        if (retBatchId && returnItemId) {
          await client.query(
            `INSERT INTO sale_return_cost_allocations (
              return_id, return_item_id, batch_id, quantity, unit_cost, total_cost, created_at
            ) VALUES ($1, $2, $3, $4, $5, $6, NOW())`,
            [returnId, returnItemId, retBatchId, qtyToRestore, it.unit_cost, qtyToRestore * it.unit_cost]
          );
        }
      }

      await client.query('UPDATE sale_items SET returned_quantity = returned_quantity + $1 WHERE id = $2', [it.quantity, it.sale_item_id]);
      await client.query('UPDATE products SET quantity = quantity + $1, updated_at = NOW() WHERE id = $2', [it.quantity, it.product_id]);

      const curProdRes = await client.query('SELECT quantity FROM products WHERE id = $1', [it.product_id]);
      const curStock = curProdRes.rows[0]?.quantity || 0;

      await client.query(
        `INSERT INTO inventory_movements (product_id, quantity_change, stock_after, movement_type, reference_type, reference_id, user_id, notes, created_at)
         VALUES ($1, $2, $3, 'return', 'return', $4, $5, $6, NOW())`,
        [it.product_id, it.quantity, curStock, returnId, req.user.user_id, `گەڕانەوە لە پسووڵەی ${sale.receipt_number}`]
      );
    }

    // Debt adjustment vs Cash refund
    let debtDeduction = 0;
    let cashRefund = totalRefund;

    if (sale.customer_id) {
      const debtRes = await client.query("SELECT id, remaining_balance FROM customer_debts WHERE sale_id = $1 AND status != 'paid' ORDER BY id DESC LIMIT 1 FOR UPDATE", [sale_id]);
      const debtRow = debtRes.rows[0];

      if (debtRow && Number(debtRow.remaining_balance) > 0) {
        const remBal = Number(debtRow.remaining_balance);
        if (totalRefund <= remBal) {
          debtDeduction = totalRefund;
          cashRefund = 0;
        } else {
          debtDeduction = remBal;
          cashRefund = totalRefund - remBal;
        }

        const newBal = Math.max(0, remBal - debtDeduction);
        const status = newBal === 0 ? 'paid' : 'partial';

        await client.query('UPDATE customer_debts SET remaining_balance = $1, status = $2, updated_at = NOW() WHERE id = $3', [newBal, status, debtRow.id]);
        await client.query('UPDATE customers SET current_debt = GREATEST(0, current_debt - $1), total_spent = GREATEST(0, total_spent - $2), updated_at = NOW() WHERE id = $3', [debtDeduction, totalRefund, sale.customer_id]);
      }
    }

    const totalsRes = await client.query('SELECT SUM(quantity)::int as sold, SUM(returned_quantity)::int as ret FROM sale_items WHERE sale_id = $1', [sale_id]);
    const totals = totalsRes.rows[0];
    const newSaleStatus = totals && totals.ret >= totals.sold ? 'returned' : 'partially_returned';
    await client.query('UPDATE sales SET status = $1, updated_at = NOW() WHERE id = $2', [newSaleStatus, sale_id]);

    if (cashRefund > 0) {
      await recordCashTransaction(client, {
        cashAccountId: 1,
        transactionType: 'CUSTOMER_REFUND',
        direction: 'OUT',
        amount: cashRefund,
        referenceType: 'return',
        referenceId: returnId,
        description: `گەڕاندنەوەی نەقدی فرۆشتن: پسووڵەی ${sale.receipt_number} (${returnNumber})`,
        userId: req.user.user_id,
      });
    }

    await client.query('COMMIT');

    logAudit(req.user.user_id, req.user.name, 'CREATE_RETURN', 'RETURN', returnId, '', `گەڕاندنەوەی پسووڵە: ${returnNumber} بۆ ${sale.receipt_number}`, req.ip);

    res.status(201).json({
      success: true,
      data: {
        id: returnId,
        return_number: returnNumber,
        total_refund: totalRefund,
        debt_deduction: debtDeduction,
        cash_refund: cashRefund,
        status: newSaleStatus,
      },
      message: 'گەڕاندنەوەی کاڵا بە سەرکەوتوویی تۆمارکرا',
    });
  } catch (err) {
    await client.query('ROLLBACK');
    console.error('Return error:', err);
    res.status(500).json({ success: false, message: 'هەڵە لە گەڕاندنەوەی کاڵا' });
  } finally {
    client.release();
  }
});

