app.post('/api/inventory/adjust', authenticateToken, requireAdmin, async (req, res) => {
  const { product_id, adjustment_type, quantity, new_quantity, movement_type, reason, notes } = req.body || {};
  if (!product_id) return res.status(400).json({ success: false, message: 'زانیاری نادروستە: کاڵا دیاری نەکراوە' });

  const client = await getClient();
  try {
    await client.query('BEGIN');

    const prodRes = await client.query('SELECT * FROM products WHERE id = $1 FOR UPDATE', [product_id]);
    const prod = prodRes.rows[0];
    if (!prod) {
      await client.query('ROLLBACK');
      return res.status(404).json({ success: false, message: 'کاڵا نەدۆزرایەوە' });
    }

    const curStock = Number(prod.quantity) || 0;
    let diff = 0;
    let newStock = curStock;

    if (new_quantity !== undefined && new_quantity !== null && !isNaN(Number(new_quantity))) {
      newStock = Math.max(0, parseInt(new_quantity, 10));
      diff = newStock - curStock;
    } else {
      const q = parseInt(quantity, 10) || 0;
      if (adjustment_type === 'add') {
        diff = q;
        newStock = curStock + q;
      } else if (adjustment_type === 'reduce') {
        diff = -q;
        newStock = Math.max(0, curStock - q);
      } else if (adjustment_type === 'set') {
        diff = q - curStock;
        newStock = Math.max(0, q);
      } else if (adjustment_type === 'damage') {
        diff = -q;
        newStock = Math.max(0, curStock - q);
      }
    }

    if (diff === 0) {
      await client.query('ROLLBACK');
      return res.json({ success: true, message: 'هیچ گۆڕانکارییەک لە ژمارەی کاڵا نەکرا' });
    }

    const effectiveReason = reason || movement_type || adjustment_type || (diff > 0 ? 'stock_correction' : 'correction');

    if (diff > 0) {
      await client.query(
        `INSERT INTO inventory_batches (
          product_id, supplier_id, batch_type, batch_number,
          original_quantity, remaining_quantity, unit_cost, purchase_date, notes, created_at, updated_at
        ) VALUES ($1, $2, 'MANUAL_ADJUSTMENT', $3, $4, $4, $5, CURRENT_DATE, $6, NOW(), NOW())`,
        [product_id, prod.supplier_id || null, `ADJ-${product_id}-${Date.now()}`, diff, Number(prod.purchase_price) || 0, notes || 'زیادکردنی دەستی لە مەخزەن']
      );
    } else if (diff < 0) {
      await allocateFifoStock(client, product_id, Math.abs(diff), Number(prod.purchase_price) || 0);
    }

    await client.query('UPDATE products SET quantity = $1, updated_at = NOW() WHERE id = $2', [newStock, product_id]);

    await client.query(
      `INSERT INTO inventory_movements (product_id, quantity_change, stock_after, movement_type, user_id, notes, created_at)
       VALUES ($1, $2, $3, $4, $5, $6, NOW())`,
      [product_id, diff, newStock, effectiveReason, req.user.user_id, notes || `ڕێکخستنەوەی دەستی: ${curStock} -> ${newStock}`]
    );

    await client.query('COMMIT');
    logAudit(req.user.user_id, req.user.name, 'STOCK_ADJUST', 'INVENTORY', product_id, `${curStock}`, `${newStock}`, req.ip);

    res.json({ success: true, message: 'مەخزەن بە سەرکەوتوویی ڕێکخرایەوە', data: { quantity: newStock } });
  } catch (err) {
    await client.query('ROLLBACK');
    res.status(500).json({ success: false, message: 'هەڵە لە ڕێکخستنی مەخزەن' });
  } finally {
    client.release();
  }
});

