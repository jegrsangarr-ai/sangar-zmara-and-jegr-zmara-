// Comprehensive Company Account Overview (Header, Drivers, Vehicles, Invoices, Debts, Payments, Driver Breakdown, Vehicle Breakdown)
app.get('/api/companies/:id/account', authenticateToken, async (req, res) => {
  try {
    const compId = req.params.id;

    // 1. Company Core Info
    const compRes = await query(`
      SELECT 
        c.*,
        (SELECT COUNT(*)::int FROM company_drivers d WHERE d.company_id = c.id AND d.is_active = 1) as driver_count,
        (SELECT COUNT(*)::int FROM company_vehicles v WHERE v.company_id = c.id AND v.is_active = 1) as vehicle_count
      FROM companies c
      WHERE c.id = $1
    `, [compId]);

    const company = compRes.rows[0];
    if (!company) {
      return res.status(404).json({ success: false, message: 'کۆمپانیا نەدۆزرایەوە' });
    }

    // 2. Drivers list with calculated driver-related debt
    const driversRes = await query(`
      SELECT 
        d.*,
        v.plate_number as vehicle_plate,
        v.vehicle_number,
        v.truck_brand,
        COALESCE(
          (SELECT SUM(cd.remaining_amount)::bigint FROM company_debts cd WHERE cd.driver_id = d.id AND cd.status != 'paid'),
          0
        ) as related_debt,
        COALESCE(
          (SELECT COUNT(*)::int FROM sales s WHERE s.company_driver_id = d.id),
          0
        ) as purchase_count,
        COALESCE(
          (SELECT SUM(s.total_amount)::bigint FROM sales s WHERE s.company_driver_id = d.id),
          0
        ) as total_driver_purchases
      FROM company_drivers d
      LEFT JOIN company_vehicles v ON d.vehicle_id = v.id
      WHERE d.company_id = $1 AND d.is_active = 1
      ORDER BY d.id DESC
    `, [compId]);

    // 3. Vehicles list with calculated vehicle-related debt
    const vehiclesRes = await query(`
      SELECT 
        v.*,
        d.full_name as driver_name,
        d.phone as driver_phone,
        COALESCE(
          (SELECT SUM(cd.remaining_amount)::bigint FROM company_debts cd WHERE cd.vehicle_id = v.id AND cd.status != 'paid'),
          0
        ) as related_debt,
        COALESCE(
          (SELECT COUNT(*)::int FROM sales s WHERE s.company_vehicle_id = v.id),
          0
        ) as purchase_count,
        COALESCE(
          (SELECT SUM(s.total_amount)::bigint FROM sales s WHERE s.company_vehicle_id = v.id),
          0
        ) as total_vehicle_purchases
      FROM company_vehicles v
      LEFT JOIN company_drivers d ON v.driver_id = d.id
      WHERE v.company_id = $1 AND v.is_active = 1
      ORDER BY v.id DESC
    `, [compId]);

    // 4. Company Debts (Unpaid / Partial / Paid)
    const debtsRes = await query(`
      SELECT 
        cd.*,
        s.receipt_number,
        s.sale_date,
        s.sale_time,
        s.total_amount as sale_total_amount,
        s.paid_amount as sale_paid_amount,
        s.payment_type as sale_payment_type,
        d.full_name as driver_name,
        d.phone as driver_phone,
        v.plate_number as vehicle_plate,
        v.vehicle_number,
        v.truck_brand,
        u.name as user_name
      FROM company_debts cd
      LEFT JOIN sales s ON cd.sale_id = s.id
      LEFT JOIN company_drivers d ON cd.driver_id = d.id
      LEFT JOIN company_vehicles v ON cd.vehicle_id = v.id
      LEFT JOIN users u ON s.user_id = u.id
      WHERE cd.company_id = $1
      ORDER BY cd.id DESC
    `, [compId]);

    // Attach items for each debt's sale
    for (const debt of debtsRes.rows) {
      if (debt.sale_id) {
        const itemsRes = await query(`
          SELECT product_name, part_number, quantity, unit_price, total_price
          FROM sale_items
          WHERE sale_id = $1
          ORDER BY id ASC
        `, [debt.sale_id]);
        debt.items = itemsRes.rows;
      } else {
        debt.items = [];
      }
    }

    // 5. Invoices (All sales for company)
    const salesRes = await query(`
      SELECT 
        s.*,
        d.full_name as driver_name,
        v.plate_number as vehicle_plate,
        v.vehicle_number,
        v.truck_brand,
        u.name as user_name
      FROM sales s
      LEFT JOIN company_drivers d ON s.company_driver_id = d.id
      LEFT JOIN company_vehicles v ON s.company_vehicle_id = v.id
      LEFT JOIN users u ON s.user_id = u.id
      WHERE s.company_id = $1
      ORDER BY s.id DESC
    `, [compId]);

    for (const s of salesRes.rows) {
      const itemsRes = await query(`
        SELECT product_name, part_number, quantity, unit_price, total_price
        FROM sale_items
        WHERE sale_id = $1
        ORDER BY id ASC
      `, [s.id]);
      s.items = itemsRes.rows;
    }

    // 6. Payment History
    const paymentsRes = await query(`
      SELECT 
        p.*,
        u.name as received_by_name,
        cd.sale_id,
        s.receipt_number as debt_receipt_number
      FROM company_debt_payments p
      LEFT JOIN users u ON p.received_by = u.id
      LEFT JOIN company_debts cd ON p.company_debt_id = cd.id
      LEFT JOIN sales s ON cd.sale_id = s.id
      WHERE p.company_id = $1
      ORDER BY p.id DESC
    `, [compId]);

    // 7. Breakdown "هەر سایق چی بردووە؟" (What did each driver take?)
    const driverBreakdown = [];
    for (const d of driversRes.rows) {
      const dSales = salesRes.rows.filter(s => s.company_driver_id === d.id);
      driverBreakdown.push({
        driver_id: d.id,
        driver_name: d.full_name,
        driver_phone: d.phone,
        vehicle_plate: d.vehicle_plate,
        total_purchases: d.total_driver_purchases,
        related_debt: d.related_debt,
        sales_count: dSales.length,
        invoices: dSales,
      });
    }

    // Include any sales that had no specific driver assigned
    const unassignedSales = salesRes.rows.filter(s => !s.company_driver_id);
    if (unassignedSales.length > 0) {
      const unassignedDebt = debtsRes.rows
        .filter(d => !d.driver_id && d.status !== 'paid')
        .reduce((sum, d) => sum + Number(d.remaining_amount), 0);
      const unassignedPurchases = unassignedSales.reduce((sum, s) => sum + Number(s.total_amount), 0);

      driverBreakdown.push({
        driver_id: null,
        driver_name: 'ڕاستەوخۆ بەناوی کۆمپانیا (بێ دیاریکردنی سایق)',
        driver_phone: '',
        vehicle_plate: '',
        total_purchases: unassignedPurchases,
        related_debt: unassignedDebt,
        sales_count: unassignedSales.length,
        invoices: unassignedSales,
      });
    }

    // 8. Breakdown by Vehicle ("مێژووی کڕینی ئۆتۆمبێلەکان")
    const vehicleBreakdown = [];
    for (const v of vehiclesRes.rows) {
      const vSales = salesRes.rows.filter(s => s.company_vehicle_id === v.id);
      vehicleBreakdown.push({
        vehicle_id: v.id,
        plate_number: v.plate_number,
        vehicle_number: v.vehicle_number,
        truck_brand: v.truck_brand,
        truck_model: v.truck_model,
        driver_name: v.driver_name,
        total_purchases: v.total_vehicle_purchases,
        related_debt: v.related_debt,
        sales_count: vSales.length,
        invoices: vSales,
      });
    }

    res.json({
      success: true,
      data: {
        company,
        drivers: driversRes.rows,
        vehicles: vehiclesRes.rows,
        debts: debtsRes.rows,
        invoices: salesRes.rows,
        payments: paymentsRes.rows,
        driver_breakdown: driverBreakdown,
        vehicle_breakdown: vehicleBreakdown,
      },
    });
  } catch (err) {
    console.error('Error fetching company account:', err);
    res.status(500).json({ success: false, message: 'هەڵە لە وەرگرتنی هەژماری کۆمپانیا' });
  }
});

