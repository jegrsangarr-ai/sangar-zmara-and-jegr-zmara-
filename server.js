// List all SQLite backups
app.get('/api/backup/list', authenticateToken, requireAdmin, async (req, res) => {
  try {
    const backupDir = path.join(process.cwd(), 'backups');
    if (!fs.existsSync(backupDir)) {
      fs.mkdirSync(backupDir, { recursive: true });
    }

    const files = fs.readdirSync(backupDir)
      .filter(f => f.endsWith('.db') || f.endsWith('.json'))
      .map(filename => {
        const filePath = path.join(backupDir, filename);
        const stats = fs.statSync(filePath);
        return {
          filename,
          size_bytes: stats.size,
          size_formatted: stats.size > 1024 * 1024 
            ? `${(stats.size / (1024 * 1024)).toFixed(2)} MB` 
            : `${(stats.size / 1024).toFixed(1)} KB`,
          created_at: stats.mtime.toISOString(),
          type: filename.endsWith('.db') ? 'SQLite Database (.db)' : 'JSON Export (.json)',
        };
      })
      .sort((a, b) => new Date(b.created_at) - new Date(a.created_at));

    res.json({ success: true, data: files });
  } catch (err) {
    console.error('List backups error:', err);
    res.status(500).json({ success: false, message: 'هەڵە لە لیستی باکئەپەکان' });
  }
});

