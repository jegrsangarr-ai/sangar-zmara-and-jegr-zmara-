    await query(`ALTER TABLE cash_sessions ADD COLUMN IF NOT EXISTS difference BIGINT DEFAULT 0`).catch(() => {});
    await query(`ALTER TABLE cash_transactions ADD COLUMN IF NOT EXISTS cash_account_id BIGINT DEFAULT 1`).catch(() => {});
    await query(`ALTER TABLE cash_transactions ADD COLUMN IF NOT EXISTS cash_session_id BIGINT`).catch(() => {});
