const updateUserHandler = async (req, res) => {
  const userId = req.params.id;
  const { name, full_name, email, role_id, phone, status, is_active } = req.body || {};
  const cleanName = (full_name || name || '').trim();
  const cleanEmail = (email || '').trim().toLowerCase();

  try {
    const userRes = await query('SELECT * FROM users WHERE id = $1', [userId]);
    const user = userRes.rows[0];
    if (!user) {
      return res.status(404).json({ success: false, message: 'بەکارهێنەر نەدۆزرایەوە' });
    }

    const updatedName = cleanName || user.name;
    const updatedEmail = cleanEmail || user.email;
    const updatedRoleId = role_id ? Number(role_id) : user.role_id;
    const updatedPhone = phone !== undefined ? phone : (user.phone || '');
    let updatedActive = user.is_active;
    if (status !== undefined) updatedActive = status === 'active' ? 1 : 0;
    if (is_active !== undefined) updatedActive = (is_active === true || is_active === 1) ? 1 : 0;

    await query(
      `UPDATE users
       SET name = $1, email = $2, role_id = $3, phone = $4, is_active = $5, updated_at = NOW()
       WHERE id = $6`,
      [updatedName, updatedEmail, updatedRoleId, updatedPhone, updatedActive, userId]
    );

    await logAudit(
      req.user?.id,
      req.user?.email,
      'USER_UPDATED',
      'USER',
      userId,
      JSON.stringify({ name: user.name, email: user.email, role_id: user.role_id, is_active: user.is_active }),
      JSON.stringify({ name: updatedName, email: updatedEmail, role_id: updatedRoleId, is_active: updatedActive }),
      req.ip
    );

    res.json({ success: true, message: 'زانیارییەکانی بەکارهێنەر بە سەرکەوتوویی نوێکرایەوە' });
  } catch (err) {
    console.error('❌ Update user error:', err);
    res.status(500).json({ success: false, message: 'هەڵە لە نوێکردنەوەی بەکارهێنەر' });
  }
};

app.put('/api/users/:id', authenticateToken, requireAdmin, updateUserHandler);
